import { Router } from "express";
import { authenticate, requireRole } from "../middlewares/auth.js";
import { rateLimit, trustedOrigin } from "../middlewares/security.js";
import { authController as auth } from "../controllers/auth.controller.js";
import { projectController as projects } from "../controllers/project.controller.js";
import { matchController as matches } from "../controllers/match.controller.js";
import { userController as users } from "../controllers/user.controller.js";
export const routes = Router();
const authRoutes = Router();
authRoutes.use(rateLimit("auth", 30, 900), (_req, res, next) => {
  res.setHeader("Cache-Control", "no-store");
  next();
});
authRoutes.post("/verifications", trustedOrigin, auth.verification);
authRoutes.post("/register", trustedOrigin, auth.register);
authRoutes.post("/login", trustedOrigin, auth.login);
authRoutes.post("/admin/login", trustedOrigin, auth.admin);
authRoutes.post("/password/reset", trustedOrigin, auth.reset);
authRoutes.post("/refresh", trustedOrigin, auth.refresh);
authRoutes.post("/logout", trustedOrigin, auth.logout);
authRoutes.get("/oauth/:provider", auth.oauthStart);
authRoutes.post("/oauth/:provider/link", trustedOrigin, authenticate, requireRole("DEVELOPER"), auth.oauthLink);
authRoutes.get("/oauth/:provider/callback", auth.oauthCallback);
routes.use("/auth", authRoutes);
routes.get("/projects", projects.list);
routes.get("/projects/:id", projects.detail);
routes.use(authenticate, (_req, res, next) => {
  res.setHeader("Cache-Control", "no-store");
  next();
});
routes.get("/users/me", users.me);
routes.patch("/users/me", users.update);
const merchant = Router();
merchant.use(requireRole("MERCHANT"));
merchant.get("/matches", matches.mine);
merchant.post("/matches", matches.adopt);
merchant.post("/matches/:id/revoke", matches.revoke);
routes.use("/merchant", merchant);
const developer = Router();
developer.use(requireRole("DEVELOPER"));
developer.get("/projects", projects.mine);
developer.post("/projects", projects.create);
developer.put("/projects/:id", projects.edit);
developer.get("/revocations", matches.revocations);
developer.post("/revocations/:id/declare", matches.declare);
routes.use("/developer", developer);
const admin = Router();
admin.use(requireRole("ADMIN"));
admin.get("/projects", projects.adminList);
admin.post("/projects/:id/moderation", projects.moderate);
admin.get("/projects/:id/history", projects.history);
admin.get("/operations", projects.operations);
routes.use("/admin", admin);
